P(f"\nThe queue (`m.last_bids`) has {len(m.last_bids)} entries — one per (short region, route to it), "
  "sorted by netback = premium − 0.01 × days. Walking down it:\n")
P("```python\nfor netback, rname in self.last_bids:\n    r = ROUTES[rname][1]\n    if shortfall[r] > 0:\n"
  "        shortfall[r] -= push(rname, shortfall[r])\n```\n")
for o in m.last_spot:
    run_sup[o] = run_sup.get(o, 0.0) + m.last_spot[o]
push_table([(i + 1, e) for i, e in enumerate(log[split + 1:])])

# the rebuilt tallies must match the model's own, or the tables above are wrong
