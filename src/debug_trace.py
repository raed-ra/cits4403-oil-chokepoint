# replay tallies from the log to show running values
run_used = {c: 0.0 for c in D.CHOKEPOINTS}
run_del = dict(dom)
run_sup = dict(m.last_contracted)
stage = 1


def push_table(entries):
    global run_sup
    P("| # | Route | Asked for (still needs) | Producer has | Room on path | Tankers | Route/pipe room | **Sent** | After: path used | After: producer left | After: buyer received |")
    P("|---|---|---|---|---|---|---|---|---|---|---|")
    for i, e in entries:
        for c in e["cps"]:
            run_used[c] += e["sent"]
        run_sup[e["origin"]] = run_sup.get(e["origin"], 0.0) - e["sent"]
        run_del[e["dest"]] += e["sent"]
        path = ", ".join(f"{c} {run_used[c]:.2f}" for c in e["cps"] if cap[c] < INF) or "no limited passage"
        pipe = f" ({e['pipe']})" if e["pipe"] else ""
        P(f"| {i} | {e['route']} | {e['need']:.2f} | {e['producer_left']:.2f} | {f2(e['passage_room'])} | "
          f"{e['tanker_room']:.1f} | {f2(e['route_room'])}{pipe} | **{e['sent']:.2f}** | {path} | "
          f"{e['origin']} {run_sup[e['origin']]:.2f} | {e['dest']} {run_del[e['dest']]:.2f} |")


split = log.index("STAGE 2")
P("\n### Step 3 — Stage 1: contracted oil, fastest route first\n")
P("```python\nfor rname in sorted(ROUTES, key=lambda k: ROUTES[k][3]):   # shortest voyage first\n"
  "    dest = ROUTES[rname][1]\n    need = want[dest] - delivered[dest]\n    if need > 0:              # only if the buyer still needs oil\n"
  "        push(rname, need)\n```\n")
P("Every one of the 37 routes is looked at in order of voyage days, but `push` is only called when "
  "the route's buyer still needs oil. Each row is one real `push()` call. **Sent** is the smallest of "
  "the five limits to its left; the last three columns are the tallies after the push.\n")
push_table([(i + 1, e) for i, e in enumerate(log[:split])])
P(f"\nRoutes skipped in Stage 1 because their buyer needed nothing: "
  f"{len(NM.ROUTES) - split} of 37.\n")
