def lines_of(fname):
    """{variable or function name: line number} for top-level definitions in a file."""
    tree = ast.parse(open(os.path.join(HERE, fname)).read())
    out = {}
    for n in ast.walk(tree):                                   # methods inside the class too
        if isinstance(n, ast.FunctionDef):
            out.setdefault(n.name, n.lineno)
    for n in tree.body:
        if isinstance(n, ast.Assign):
            for t in n.targets:
                if isinstance(t, ast.Name):
                    out.setdefault(t.id, n.lineno)
        elif isinstance(n, (ast.FunctionDef, ast.ClassDef)):
            out[n.name] = n.lineno
    return out


